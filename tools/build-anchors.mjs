/*
 * Generates app/src/main/assets/anchors.js from the user's own anchor tables:
 *   D:\AI\health\rules.md        第五节 常见食物估算锚点
 *   D:\AI\health\food-anchors.md 一（按烹调方式估油）、二（成品菜）、三（外卖速查）、五（降油动作）
 *
 * Why generate instead of hand-typing: rules.md says the same food must keep the same anchor across
 * sessions, so the app has to read the written table rather than invent a second set of numbers.
 * Run: node tools/build-anchors.mjs   (writes the asset, prints what it found)
 */
import fs from 'node:fs';
import path from 'node:path';

const RULES = 'D:/AI/health/rules.md';
const ANCHORS = 'D:/AI/health/food-anchors.md';
const OUT = 'app/src/main/assets/anchors.js';

const read = file => {
  if (!fs.existsSync(file)) throw new Error(`missing source file: ${file}`);
  return fs.readFileSync(file, 'utf8');
};

/** Rows of a GitHub-style markdown table that appear under a heading matching `heading`. */
function tableRows(text, heading, stopHeadings = []) {
  const lines = text.split(/\r?\n/);
  const start = lines.findIndex(line => line.startsWith('#') && line.includes(heading));
  if (start < 0) throw new Error(`heading not found: ${heading}`);
  const rows = [];
  for (let i = start + 1; i < lines.length; i++) {
    const line = lines[i];
    if (/^#{1,6}\s/.test(line)) {
      if (stopHeadings.length === 0 || stopHeadings.some(stop => line.includes(stop))) break;
      if (stopHeadings.length) break;
    }
    if (!line.trim().startsWith('|')) continue;
    if (/^\|[\s:|-]+\|$/.test(line.trim())) continue;
    const cells = line.trim().replace(/^\||\|$/g, '').split('|').map(cell => cell.trim());
    rows.push(cells);
  }
  return rows;
}

/** First number in a cell, ignoring thousands separators. Returns null when there is none. */
function num(cell) {
  if (cell === undefined) return null;
  const match = String(cell).replace(/,/g, '').match(/-?\d+(?:\.\d+)?/);
  return match ? Number(match[0]) : null;
}
function range(cell) {
  const cleaned = String(cell ?? '').replace(/,/g, '');
  const found = cleaned.match(/\d+(?:\.\d+)?/g);
  if (!found || !found.length) return [null, null];
  const values = found.map(Number);
  return [values[0], values.length > 1 ? values[1] : values[0]];
}
function stripBold(cell) {
  return String(cell ?? '').replace(/\*\*/g, '').replace(/[（(]含汤[)）]/g, '').trim();
}

const rulesText = read(RULES);
const anchorsText = read(ANCHORS);

// rules.md 第五节: | 食物 | 分量 | 热量 | 蛋白 | 脂肪 |
const basic = tableRows(rulesText, '常见食物估算锚点')
  .filter(cells => cells.length >= 5)
  .map(([name, portion, calories, protein, fat]) => ({
    name: stripBold(name), portion: stripBold(portion),
    grams: num(portion), calories: num(calories), protein: num(protein), fat: num(fat),
    kind: 'ingredient'
  }))
  .filter(row => row.name && row.calories !== null);

// food-anchors.md 一: | 烹调方式 | 典型用油 | 热量 | 判断特征 |
const oilByMethod = tableRows(anchorsText, '按烹调方式估油')
  .filter(cells => cells.length >= 4)
  .map(([method, oil, kcal, hint]) => {
    const [gramsMin, gramsMax] = range(oil);
    const [kcalMin, kcalMax] = range(kcal);
    return {method: stripBold(method), gramsMin, gramsMax, kcalMin, kcalMax, hint: stripBold(hint)};
  })
  .filter(row => row.method && row.gramsMin !== null);

// food-anchors.md 二: | 菜品 | 常见份量 | 热量 | 蛋白 | 脂肪 | 用油 |
const dishes = tableRows(anchorsText, '成品菜锚点')
  .filter(cells => cells.length >= 6)
  .map(([name, portion, calories, protein, fat, oil]) => {
    const [oilMin, oilMax] = range(oil);
    return {
      name: stripBold(name), portion: stripBold(portion), grams: num(portion),
      calories: num(calories), protein: num(protein), fat: num(fat),
      oilMin, oilMax, kind: 'dish'
    };
  })
  .filter(row => row.name && row.calories !== null);

// food-anchors.md 三: | 套餐 | 热量 | 蛋白 | 用法 |
const takeout = tableRows(anchorsText, '外卖常见套餐速查')
  .filter(cells => cells.length >= 4)
  .map(([name, calories, protein, note]) => ({
    name: stripBold(name), calories: num(calories), protein: num(protein), note: stripBold(note)
  }))
  .filter(row => row.name && row.calories !== null);

// food-anchors.md 五: | 动作 | 省下 |
const oilTips = tableRows(anchorsText, '把油降下来的三个动作')
  .filter(cells => cells.length >= 2)
  .map(([action, saving]) => ({action: stripBold(action), saving: stripBold(saving)}))
  .filter(row => row.action);

if (basic.length < 5 || oilByMethod.length < 5 || dishes.length < 10)
  throw new Error(`parsed too little: basic=${basic.length} oil=${oilByMethod.length} dishes=${dishes.length}`);

const payload = {basic, oilByMethod, dishes, takeout, oilTips, generatedFrom: ['rules.md#五', 'food-anchors.md#一#二#三#五']};

const asset = `/*
 * QinghengAnchors - the user's own estimation anchors, GENERATED by tools/build-anchors.mjs from
 * rules.md (第五节) and food-anchors.md (第一/二/三/五节). Do not edit by hand: rerun the generator.
 *
 * Purpose: rules.md requires the same food to keep the same numbers across sessions. Shipping the
 * written table into the app (and into the model prompts) is what stops the drift.
 * Values are estimates with the ±15% (cooked dishes ±15~25%) error the source files declare.
 */
(function (root, factory) {
  'use strict';
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.QinghengAnchors = api;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  const data = ${JSON.stringify(payload, null, 2)};

  function norm(text) {
    return String(text || '').toLowerCase().replace(/[\\s·、,，.。()（）]/g, '');
  }
  /** Anchors whose name appears in the query (or the query in the name), best match first. */
  function search(query, limit) {
    const q = norm(query);
    if (!q) return [];
    const pool = data.dishes.concat(data.basic);
    const hits = [];
    for (const row of pool) {
      const name = norm(row.name);
      if (!name) continue;
      if (name === q) hits.push({row, score: 3});
      else if (name.includes(q) || q.includes(name)) hits.push({row, score: 2});
      else if (row.kind === 'dish' && q.length > 1 && [...q].every(ch => name.includes(ch))) hits.push({row, score: 1});
    }
    hits.sort((a, b) => b.score - a.score || String(a.row.name).localeCompare(String(b.row.name)));
    const seen = new Set();
    const out = [];
    for (const hit of hits) {
      if (seen.has(hit.row.name)) continue;
      seen.add(hit.row.name);
      out.push(hit.row);
      if (limit && out.length >= limit) break;
    }
    return out;
  }
  /** Cooking-oil estimate for a cooking method mentioned in free text. */
  function oilFor(text) {
    const q = norm(text);
    if (!q) return null;
    const keys = ['白灼', '清蒸', '水煮', '凉拌', '清炒', '小炒', '炒肉', '爆炒', '干煸', '红烧', '油炸', '干锅', '黄焖', '砂锅'];
    for (const key of keys) {
      const row = data.oilByMethod.find(item => norm(item.method).includes(key));
      if (row && q.includes(norm(key))) return row;
    }
    return null;
  }
  /** Compact text block for the model prompts; bounded so it cannot blow up a request. */
  function summary(limit = 1800) {
    const lines = ['【用户既有估算锚点（必须沿用，不要另创数值）】'];
    lines.push('按烹调方式估油：' + data.oilByMethod.map(row =>
      \`\${row.method} \${row.gramsMin}~\${row.gramsMax}g(\${row.kcalMin}~\${row.kcalMax}kcal)\`).join('；'));
    lines.push('成品菜（一份）：' + data.dishes.slice(0, 20).map(row =>
      \`\${row.name} \${row.portion}≈\${row.calories}kcal/蛋白\${row.protein}g/脂肪\${row.fat}g\`).join('；'));
    if (data.basic.length) lines.push('生食材：' + data.basic.map(row =>
      \`\${row.name} \${row.portion}≈\${row.calories}kcal/蛋白\${row.protein}g/脂肪\${row.fat}g\`).join('；'));
    if (data.takeout.length) lines.push('外卖速查：' + data.takeout.map(row =>
      \`\${row.name} ≈\${row.calories}kcal\`).join('；'));
    const text = lines.join('\\n');
    return text.length > limit ? text.slice(0, limit) + '…' : text;
  }
  return {data, search, oilFor, summary};
});
`;

fs.mkdirSync(path.dirname(OUT), {recursive: true});
fs.writeFileSync(OUT, asset);
console.log(`anchors.js written: ${basic.length} ingredients, ${oilByMethod.length} cooking methods, ${dishes.length} dishes, ${takeout.length} takeout rows, ${oilTips.length} tips`);
